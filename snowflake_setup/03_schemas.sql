
-- 03: Create schemas and assign ownership.
-- Execute as SYSADMIN.

USE ROLE SYSADMIN;

-- Raw ingestion layer managed by dlt
CREATE SCHEMA IF NOT EXISTS STEAM_DB.STEAM_RAW;

-- Transformation layers managed by dbt
CREATE SCHEMA IF NOT EXISTS STEAM_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS STEAM_DB.INTERMEDIATE;
CREATE SCHEMA IF NOT EXISTS STEAM_DB.MARTS;

-- Transfer raw schema ownership to dlt
GRANT OWNERSHIP ON SCHEMA STEAM_DB.STEAM_RAW
    TO ROLE STEAM_LOADER;

-- Transfer dbt schema ownership to transformer
GRANT OWNERSHIP ON SCHEMA STEAM_DB.STAGING
    TO ROLE STEAM_TRANSFORMER;

GRANT OWNERSHIP ON SCHEMA STEAM_DB.INTERMEDIATE
    TO ROLE STEAM_TRANSFORMER;

GRANT OWNERSHIP ON SCHEMA STEAM_DB.MARTS
    TO ROLE STEAM_TRANSFORMER;
